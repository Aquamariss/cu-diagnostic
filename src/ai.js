// Персонализация текста результата через Claude API.
// Баллы, сильные стороны и зоны роста уже выбраны кодом по методике (src/scoring.js);
// модель только переписывает тексты под конкретный проект и составляет роадмап на год.
// Если ключа нет или запрос не удался — остаётся шаблонный результат.

import Anthropic from '@anthropic-ai/sdk';
import { MAX_SCORE } from '../public/js/questions.js';
import { INDICATORS } from './scoring.js';

const MODEL = process.env.ANTHROPIC_MODEL || 'claude-opus-5-5';
const EFFORT = process.env.ANTHROPIC_EFFORT || 'low';

export const aiEnabled = Boolean(process.env.ANTHROPIC_API_KEY || process.env.ANTHROPIC_AUTH_TOKEN);

const client = aiEnabled ? new Anthropic({ timeout: 120_000, maxRetries: 1 }) : null;

const SYSTEM_PROMPT = `Ты — эксперт Городского университета 2.0 по развитию городских проектов, работаешь по методологии городского продюсирования Святослава Мурунова (канвас городского проекта, критерии оценки проектов Школы городских продюсеров).

Человек прошёл диагностику своего городского проекта. Баллы уже посчитаны, сильные стороны и зоны роста уже выбраны по методике — их нельзя менять, добавлять или убирать. Твоя задача — написать персональные тексты результата и роадмап на год.

Что нужно написать:
1. strengths — для каждой выбранной сильной стороны 2–3 предложения: что именно уже получается и почему это опора для проекта. Только то, что подтверждено ответами.
2. growth_zones — для каждой выбранной зоны роста 2–3 предложения по схеме: факт → что это значит для проекта → что конкретно можно сделать.
3. potential — «Потенциал развития», 500–700 знаков. Схема: 1–2 уже имеющиеся опоры → 1–2 ключевых ограничения → что изменится, если эти ограничения снять. Это не прогноз успеха: не обещай масштабирование, доход, устойчивость или успех.
4. next_step — «Ваш ближайший шаг», 250–400 знаков. Одно конкретное действие, реалистичное на текущей стадии. Формула: действие + что проверить или получить + зачем это нужно. Строится на указанном фокусе ближайшего шага. Плохо: «Развивайте партнёрства». Хорошо: «Найдите одного партнёра для следующего мероприятия и договоритесь о конкретной роли: площадка, аудитория или экспертная поддержка».
5. roadmap — 7–9 шагов развития проекта на ближайший год, которые человек реально может сделать за год, в логичном порядке (от первых к последующим). Без разбивки по кварталам и месяцам. Каждый шаг: title — короткое конкретное действие в инфинитиве (до 90 знаков), text — 1–2 предложения: что сделать и что это даст. Шаги должны быть конкретными и привязанными к формату, аудитории и проблеме проекта, по уровню конкретики как в примерах:
   • Запустить онлайн-архив и открытую платформу для обмена моделями и методологиями.
   • Организовать серию мастер-классов и интенсивов для подготовки преемников.
   • Провести международный хакатон по моделированию городов будущего.
   • Создать пилотный проект нового типа поселения с открытым доступом к процессу и результатам.
   • Разработать и внедрить программу наставничества для молодых урбанистов.
   • Запустить подкаст или видеоканал о практике и философии урбанистики.
   Первые шаги роадмапа закрывают фокус ближайшего шага и зоны роста, дальше — запрос участника и переход на следующий уровень проекта.
6. problem_unclear — true, если описание проблемы слишком общее или непонятное.

Учёт стадии проекта:
- «Пока только идея»: рекомендовать проверку проблемы, аудитории, ценности; первых людей и партнёров; маленький тест. Избегать масштабирования, сложной финансовой модели, построения большой команды.
- «Начал первые шаги»: первый практический запуск, сбор обратной связи, уточнение ролей и ценности. Избегать советов, предполагающих уже устойчивый спрос.
- «Провёл первый пилот / мероприятие / тест»: анализ опыта, повторная проверка, улучшение формата, партнёрства, экономика. Не предполагать регулярную работу без подтверждения.
- «Проект уже работает»: устойчивость, экономика, передача ролей, партнёрства, развитие и масштабирование. Не советовать «провести первый тест» как единственный следующий шаг.

Запрос участника (что ему нужно, чтобы двигаться дальше):
- Если запрос совпадает с фокусом ближайшего шага — сделай его основой ближайшего шага.
- Если не совпадает — учти запрос, но не игнорируй более базовый дефицит; можно кратко объяснить, почему сначала стоит сделать другой шаг.
- Не рекомендуй действие, для которого ещё не собраны необходимые элементы.

Профиль участника: B2C — частный инициатор (житель, педагог, волонтёр, лидер сообщества): акцент на первых единомышленниках, малых шагах, поддержке и уверенности. B2B — бизнес, НКО, девелопер, учреждение: акцент на системном подходе, упаковке, партнёрствах, диалоге с администрацией и отдаче от проекта. Профиль влияет только на акценты, не на оценку.

Персонализация:
- Используй реальный формат проекта и называй конкретную аудиторию, если она указана.
- Используй смысл описания проблемы участника; не подменяй его более удобной проблемой.
- Если описание проблемы слишком общее или неясное — не придумывай конкретную проблему; скажи, что её стоит уточнить.

Стиль:
- Простой русский язык, обращение на «вы».
- Не оценивай личность автора. Не используй ярлыки вроде «слабый проект», «неудачный проект».
- Не придумывай факты, партнёров, доходы, ресурсы, результаты или спрос, которых нет в ответах.
- Не используй внутренние методологические термины: «баллы показателя», «Q5», «кооперация», «маршрутизатор», «зона дефицита».
- Не повторяй один и тот же вывод в разных блоках.
- Между сильными сторонами, зонами роста и потенциалом не должно быть противоречий.`;

const OUTPUT_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['strengths', 'growth_zones', 'potential', 'next_step', 'roadmap', 'problem_unclear'],
  properties: {
    strengths: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['id', 'text'],
        properties: { id: { type: 'string' }, text: { type: 'string' } },
      },
    },
    growth_zones: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['id', 'text'],
        properties: { id: { type: 'string' }, text: { type: 'string' } },
      },
    },
    potential: { type: 'string' },
    next_step: { type: 'string' },
    roadmap: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['title', 'text'],
        properties: { title: { type: 'string' }, text: { type: 'string' } },
      },
    },
    problem_unclear: { type: 'boolean' },
  },
};

function describeAnswers(record) {
  const r = record.result;
  const a = record.answers;
  const lines = [
    `Профиль участника: ${r.segment ? `${r.segment.profile} (${r.segment.label})` : 'не указан'}`,
    `Стадия проекта: ${r.stage.label}`,
    `Формат проекта: ${r.format}`,
    `Аудитория: ${r.audience || 'пока не определена'}`,
    `Описание проблемы и изменения (словами участника): «${a.q4}»`,
    `Запрос участника — что нужно, чтобы двигаться дальше: ${r.need.label}`,
    '',
    `Итог: ${r.total} из ${MAX_SCORE}. Интерпретация: ${r.resultStage.text}`,
    '',
    'Профиль показателей (балл / максимум):',
    ...r.scores.map((s) => `- ${s.id} ${s.name}: ${s.score}/${s.max}`),
    '',
    'Ответы участника по показателям:',
    ...describeScoredAnswers(a),
    '',
    'Выбранные сильные стороны (id — заголовок — базовая трактовка):',
    ...(r.strengths.length
      ? r.strengths.map((s) => `- ${s.id} — ${s.title} — ${s.text}`)
      : ['- нет показателей с максимальным баллом; strengths оставь пустым массивом']),
    '',
    'Выбранные зоны роста (id — заголовок — базовая трактовка):',
    ...(r.growthZones.length
      ? r.growthZones.map((g) => `- ${g.id} — ${g.title} (${g.score}/${g.max}) — ${g.text}`)
      : ['- нет; growth_zones оставь пустым массивом']),
    '',
    `Фокус ближайшего шага: ${r.focus ? `${r.focus} — ${INDICATORS[r.focus].growthTitle}` : 'развитие и следующий уровень проекта'}`,
    `Запрос участника совпадает с фокусом: ${r.needMatched ? 'да' : 'нет'}`,
  ];
  return lines.join('\n');
}

function describeScoredAnswers(a) {
  // Короткие подписи ответов, чтобы модель опиралась на факты, а не только на баллы.
  const pick = (map, id) => map[id] ?? id;
  const out = [];
  out.push(`- Команда: ${pick({ alone: 'только автор', helpers: 'помогают время от времени', gathering: 'собирает команду / есть постоянные участники', team: 'сформированная команда с ролями' }, a.q6)}`);
  out.push(`- Функции автора: ${(a.q7 ?? []).join(', ')}`);
  const yes = Object.entries(a.q8 ?? {}).filter(([, v]) => v === 'yes').map(([k]) => k);
  const no = Object.entries(a.q8 ?? {}).filter(([, v]) => v === 'no').map(([k]) => k);
  out.push(`- Может уверенно ответить про: ${yes.join(', ') || '—'}; пока не может: ${no.join(', ') || '—'}`);
  out.push(`- Что сделано: ${pick({ thinking: 'только обдумывает идею', started: 'первые встречи / люди / договорённости', tested: 'проверил идею на практике', regular: 'проект регулярно работает' }, a.q9)}`);
  out.push(`- Опыт: ${pick({ none: 'проект ещё не реализовывался', no_analysis: 'пробовал, но не анализировал', feedback: 'получил отзывы, выводов пока нет', analyzed: 'проанализировал и понял, что менять', changed: 'внёс изменения по итогам опыта' }, a.q10)}`);
  out.push(`- Экономика: ${pick({ unknown: 'пока не понимает', who: 'понимает, кто может платить, модели нет', model: 'понимает, кто платит, за что и затраты', sources: 'несколько источников, понимает затраты и устойчивость' }, a.q11)}`);
  out.push(`- Проверка востребованности: ${pick({ none: 'не проверял', talks: 'обсуждает со знакомыми', research: 'интервью / опросы / наблюдения', data: 'использует данные для изменений', demand: 'есть регулярный / повторный спрос' }, a.q12)}`);
  out.push(`- Уже есть ресурсы: ${(a.q13 ?? []).join(', ')}`);
  out.push(`- Без автора: ${pick({ stops: 'проект остановится', partly: 'часть работы продолжат', directions: 'отдельные направления продолжат', autonomous: 'проект продолжит работу' }, a.q14)}`);
  return out;
}

/** Возвращает персонализированный результат или null, если ИИ недоступен / ответ некорректен. */
export async function personalize(record) {
  if (!client) return null;

  const response = await client.beta.messages.create({
    model: MODEL,
    max_tokens: 16000,
    betas: ['server-side-fallback-2026-07-01'],
    fallbacks: 'default',
    output_config: {
      effort: EFFORT,
      format: { type: 'json_schema', schema: OUTPUT_SCHEMA },
    },
    system: SYSTEM_PROMPT,
    messages: [{ role: 'user', content: describeAnswers(record) }],
  });

  if (response.stop_reason === 'refusal' || response.stop_reason === 'max_tokens') {
    console.warn(`Персонализация не выполнена: stop_reason=${response.stop_reason}`);
    return null;
  }
  const text = response.content.filter((b) => b.type === 'text').map((b) => b.text).join('');
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    console.warn('Персонализация: модель вернула некорректный JSON');
    return null;
  }
  return mergeIntoResult(record.result, data);
}

/** Переносит тексты модели в результат, сохраняя выбор показателей из методики. */
export function mergeIntoResult(result, data) {
  const byId = (list) => new Map((Array.isArray(list) ? list : []).map((x) => [x?.id, x?.text]));
  const s = byId(data.strengths);
  const g = byId(data.growth_zones);
  const ok = (t) => typeof t === 'string' && t.trim().length > 20;
  const roadmap = (Array.isArray(data.roadmap) ? data.roadmap : [])
    .filter((x) => ok(x?.title + ' ' + x?.text) && x.title?.trim())
    .slice(0, 10)
    .map((x) => ({ title: x.title.trim(), text: (x.text || '').trim() }));

  return {
    ...result,
    strengths: result.strengths.map((x) => (ok(s.get(x.id)) ? { ...x, text: s.get(x.id).trim() } : x)),
    growthZones: result.growthZones.map((x) => (ok(g.get(x.id)) ? { ...x, text: g.get(x.id).trim() } : x)),
    potential: ok(data.potential) ? data.potential.trim() : result.potential,
    nextStep: ok(data.next_step) ? data.next_step.trim() : result.nextStep,
    roadmap: roadmap.length >= 5 ? roadmap : result.roadmap,
    problemUnclear: data.problem_unclear === true,
    personalized: true,
  };
}
