/** Сильные стороны: показатели с максимальным баллом, порядок — по стадии Q1. До 3 штук. */
export function pickStrengths(scores, stage) {
  return STRENGTH_PRIORITY[stage]
    .filter((id) => scores[id] === getQuestion(id).max)
    .slice(0, 3);
}

/**
 * Зоны роста: сначала наиболее низкие баллы (без нормализации к максимуму — решение заказчика),
 * при равенстве — показатели, совпадающие с запросом Q15, затем приоритет стадии Q1.
 */
export function pickGrowthZones(scores, stage, need) {
  const needIds = NEED_TO_INDICATORS[need] ?? [];
  const priority = STAGE_PRIORITY[stage];
  return SCORED_IDS.filter((id) => scores[id] < getQuestion(id).max)
    .sort((a, b) => {
      if (scores[a] !== scores[b]) return scores[a] - scores[b];
      const na = needIds.includes(a) ? 0 : 1;
      const nb = needIds.includes(b) ? 0 : 1;
      if (na !== nb) return na - nb;
      return priority.indexOf(a) - priority.indexOf(b);
    })
    .slice(0, 3);
}

/**
 * Фокус ближайшего шага (правила «Как использовать Q15»):
 * если запрос участника совпадает с одной из выбранных зон роста — шаг строится на нём,
 * иначе — на самой базовой зоне роста.
 */
export function pickFocus(growthZones, need) {
  const needIds = NEED_TO_INDICATORS[need] ?? [];
  const matched = growthZones.find((id) => needIds.includes(id));
  return { focus: matched ?? growthZones[0] ?? null, needMatched: Boolean(matched) };
}

