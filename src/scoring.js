function audienceLabel(answers) {
  const ids = answers.q3 ?? [];
  if (!ids.length || ids.includes('unknown')) return '';
  return ids
    .map((id) => (id === 'other' ? answers.q3_other || '' : optionLabel('q3', id).toLowerCase()))
    .filter(Boolean)
    .join(', ');
}

function formatLabel(answers) {
  if (answers.q2 === 'other') return answers.q2_other || 'Другое';
  return optionLabel('q2', answers.q2);
}

