const clip = (s, n) => String(s ?? '').trim().slice(0, n);

/** Приводит ответы к ожидаемой форме и возвращает { answers, errors }. */
export function normalizeAnswers(raw = {}) {
  const answers = {};
  const errors = [];
  for (const q of QUESTIONS) {
    const v = raw[q.id];
    if (q.type === 'single') {
      if (!q.options.some((o) => o.id === v)) {
        errors.push(q.id);
        continue;
      }
      answers[q.id] = v;
      const opt = q.options.find((o) => o.id === v);
      if (opt.withText) answers[`${q.id}_other`] = clip(raw[`${q.id}_other`], 200);
    } else if (q.type === 'multi') {
      const ids = Array.isArray(v) ? [...new Set(v)].filter((id) => q.options.some((o) => o.id === id)) : [];
      if (!ids.length) {
        errors.push(q.id);
        continue;
      }
      const exclusive = ids.find((id) => q.options.find((o) => o.id === id).exclusive);
      answers[q.id] = exclusive ? [exclusive] : ids;
      if (answers[q.id].includes('other')) answers[`${q.id}_other`] = clip(raw[`${q.id}_other`], 200);
    } else if (q.type === 'text') {
      const text = clip(v, q.maxLength);
      if (text.length < (q.minLength || 1)) {
        errors.push(q.id);
        continue;
      }
      answers[q.id] = text;
    } else if (q.type === 'matrix') {
      const out = {};
      for (const row of q.rows) {
        const cell = v?.[row.id];
        if (!q.columns.some((c) => c.id === cell)) {
          errors.push(q.id);
          break;
        }
        out[row.id] = cell;
      }
      if (Object.keys(out).length === q.rows.length) answers[q.id] = out;
    }
  }
  return { answers, errors };
}

