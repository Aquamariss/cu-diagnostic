function buildNextStep({ focus, needMatched, need, stage }) {
  const group = stageGroup(stage);
  let text = NEXT_STEPS[focus ?? 'none'][group];
  if (focus && !needMatched && need && need !== 'unknown') {
    text += ` Ваш запрос «${optionLabel('q15', need).toLowerCase()}» тоже важен — к нему будет проще перейти, когда этот шаг будет сделан.`;
  }
  return text;
}

function buildRoadmap({ growthZones, focus, need, stage }) {
  const order = [];
  if (focus) order.push(focus);
  for (const id of growthZones) if (!order.includes(id)) order.push(id);
  for (const id of NEED_TO_INDICATORS[need] ?? []) if (!order.includes(id)) order.push(id);
  for (const id of STAGE_PRIORITY[stage]) if (!order.includes(id)) order.push(id);

  const steps = [];
  const perIndicator = (id, i) => (i < 2 ? 2 : 1);
  order.forEach((id, i) => {
    if (steps.length >= 7) return;
    const pool = ROADMAP_POOL[id].filter((s) => s.stages.includes(stage));
    for (const s of pool.slice(0, perIndicator(id, i))) {
      if (steps.length < 7) steps.push({ title: s.title, text: s.text, indicator: id });
    }
  });
  steps.push({ ...STAGE_NEXT_LEVEL[stage], indicator: null });
  return steps;
}

/** Полный шаблонный результат. */
export function buildResult({ answers, segment }) {
  const { scores, total } = computeScores(answers);
  const stage = answers.q1;
  const need = answers.q15;
  const strengths = pickStrengths(scores, stage);
  const growthZones = pickGrowthZones(scores, stage, need);
  const { focus, needMatched } = pickFocus(growthZones, need);
  const seg = SEGMENTS.find((s) => s.id === segment);

  return {
    total,
    max: MAX_SCORE,
    resultStage: resultStage(total),
    stage: { id: stage, label: optionLabel('q1', stage) },
    format: formatLabel(answers),
    audience: audienceLabel(answers),
    problem: answers.q4,
    need: { id: need, label: optionLabel('q15', need) },
    segment: seg ? { id: seg.id, label: seg.label, profile: seg.profile } : null,
    scores: SCORED_IDS.map((id) => ({ id, name: INDICATORS[id].name, score: scores[id], max: getQuestion(id).max })),
    strengths: strengths.map((id) => ({
      id,
      title: INDICATORS[id].strengthTitle,
      score: scores[id],
      max: getQuestion(id).max,
      text: INDICATORS[id].strengthText,
    })),
    growthZones: growthZones.map((id) => ({
      id,
      title: INDICATORS[id].growthTitle,
      score: scores[id],
      max: getQuestion(id).max,
      text: INDICATORS[id].growthText[scores[id]],
    })),
    focus,
    needMatched,
    potential: buildPotential({ strengths, growthZones, stage, total }),
    nextStep: buildNextStep({ focus, needMatched, need, stage }),
    roadmap: buildRoadmap({ growthZones, focus, need, stage }),
    personalized: false,
  };
}
