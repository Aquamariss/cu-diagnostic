/**
 * Q7 — роль автора. Методика: важно не количество функций, а то, соединяет ли автор
 * разные элементы проекта. Автоматическое правило (временное, согласовано с заказчиком):
 *   0 — отмечены только операционные функции (запуск, управление, «всё делаю сам»);
 *   1 — есть хотя бы одна функция, связанная с развитием проекта;
 *   2 — охвачены минимум 3 из 4 частей проекта (ценность и аудитория / люди и партнёры /
 *       ресурсы и город / результаты) и не отмечено «всё делаю сам».
 */
export function scoreQ7(selected = []) {
  const q = getQuestion('q7');
  const groups = new Set(
    selected.map((id) => q.options.find((o) => o.id === id)?.group).filter(Boolean),
  );
  if (groups.size === 0) return 0;
  if (groups.size >= 3 && !selected.includes('all_myself')) return 2;
  return 1;
}

export function scoreQ8(matrix = {}) {
  const yes = Object.values(matrix).filter((v) => v === 'yes').length;
  if (yes >= 6) return 1;
  if (yes >= 3) return 0.5;
  return 0;
}

export function scoreQ13(selected = []) {
  const count = selected.filter((id) => id !== 'none').length;
  if (count >= 5) return 2;
  if (count >= 2) return 1;
  return 0;
}

export function computeScores(answers) {
  const scores = {};
  for (const id of SCORED_IDS) {
    const q = getQuestion(id);
    if (id === 'q7') scores[id] = scoreQ7(answers.q7);
    else if (id === 'q8') scores[id] = scoreQ8(answers.q8);
    else if (id === 'q13') scores[id] = scoreQ13(answers.q13);
    else scores[id] = q.options.find((o) => o.id === answers[id])?.score ?? 0;
  }
  const total = Object.values(scores).reduce((a, b) => a + b, 0);
  return { scores, total: Math.min(total, MAX_SCORE) };
}

